
console.log("----- Assignment Operators -----");

// 1. Assignment (=)
let a = 10;
console.log("Assignment:", a);

// 2. Addition Assignment (+=)
let b = 10;
b += 5;  // b = b + 5
console.log("Addition Assignment:", b);

// 3. Subtraction Assignment (-=)
let c = 10;
c -= 5;  // c = c - 5
console.log("Subtraction Assignment:", c);

// 4. Multiplication Assignment (*=)
let d = 10;
d *= 5;  // d = d * 5
console.log("Multiplication Assignment:", d);

// 5. Division Assignment (/=)
let e = 10;
e /= 5;  // e = e / 5
console.log("Division Assignment:", e);

// 6. Remainder Assignment (%=)
let f = 10;
f %= 3;  // f = f % 3
console.log("Remainder Assignment:", f);

// 7. Exponentiation Assignment (**=)
let g = 2;
g **= 3; // g = g ** 3
console.log("Exponentiation Assignment:", g);

// 8. Left Shift Assignment (<<=)
let h = 5;
h <<= 1; // h = h << 1
console.log("Left Shift Assignment:", h);

// 9. Right Shift Assignment (>>=)
let i = 8;
i >>= 1; // i = i >> 1
console.log("Right Shift Assignment:", i);
