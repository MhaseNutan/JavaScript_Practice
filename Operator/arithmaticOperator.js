let a = 20;
let b = 6;

// 1. Addition (+)
console.log("Addition:", a + b);

// 2. Subtraction (-)
console.log("Subtraction:", a - b);

// 3. Multiplication (*)
console.log("Multiplication:", a * b);

// 4. Division (/)
console.log("Division:", a / b);

// 5. Modulus (%) - returns the remainder
console.log("Modulus:", a % b);

// 6. Exponentiation (**) - power
console.log("Exponentiation:", a ** b);

// 7. Increment (++)
let x = 5;
x++;
console.log("Increment:", x);

// 8. Decrement (--)
let y = 5;
y--;
console.log("Decrement:", y);

// 9. Operator with assignment
let c = 10;
c += 5;
console.log("Addition Assignment:", c);

let d = 10;
d -= 5;
console.log("Subtraction Assignment:", d);

let e = 10;
e *= 5;
console.log("Multiplication Assignment:", e);

let f = 10;
f /= 5;
console.log("Division Assignment:", f);

let g = 10;
g %= 3;
console.log("Modulus Assignment:", g);
