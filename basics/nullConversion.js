let value = null;

// 1. null to Number
console.log("null to Number:", Number(value));

// 2. null to String
console.log("null to String:", String(value));

// 3. null to Boolean
console.log("null to Boolean:", Boolean(value));

// 4. Type of null
console.log("Type of null:", typeof value);

// 5. null with addition
console.log("null + 10:", value + 10);

// 6. null with subtraction
console.log("null - 5:", value - 5);

// 7. null with multiplication
console.log("null * 5:", value * 5);

// 8. null with comparison
console.log("null == undefined:", null == undefined);
console.log("null === undefined:", null === undefined);



